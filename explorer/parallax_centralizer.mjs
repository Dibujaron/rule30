// Parallax, 2026-09-13.  The GEOMETRIC analogue of the polymorphism clone.
//
// A polymorphism of the local relation is an operation g on cells commuting
// with the local function f.  The geometric analogue is an operation on whole
// CONFIGURATIONS commuting with the whole map F = rule 30 -- i.e. a cellular
// automaton in rule 30's centraliser.  Unary case first (the centraliser
// proper), then the k-ary case, which is the honest picture-level polymorphism:
// a block map G : (S^Z)^k -> S^Z with G(F x_1, ..., F x_k) = F(G(x_1,...,x_k)).
//
// Equality of two block maps of radius R is decided by all windows of length
// 2R+1, so every check below is exhaustive, not sampled.

const F = (l, c, r) => l ^ (c | r);

// ---------------------------------------------------------------- unary case
// G of radius r has a table of 2^(2r+1) bits.  G∘F = F∘G has radius r+1, so
// test every window of length 2(r+1)+1 = 2r+3.
function unaryCentraliser(r, cap = 1e7) {
  const nEntries = 1 << (2 * r + 1);
  const winLen = 2 * r + 3;
  const nWin = 1 << winLen;
  // For each window (bits w[0..winLen-1], position j has w[j + r + 1] for j in -(r+1)..(r+1))
  // build the constraint:  T[idxA] == F(T[i-1], T[i0], T[i1])
  const cons = [];
  const at = (w, j) => (w >> (j + r + 1)) & 1;   // cell j of the window
  for (let w = 0; w < nWin; w++) {
    // left side: G applied to F(w) at centre.  F(w) at cell j (|j| <= r):
    let idxA = 0;
    for (let j = -r; j <= r; j++) {
      const v = F(at(w, j - 1), at(w, j), at(w, j + 1));
      idxA |= v << (j + r);      // table index: bit (j+r) is cell j
    }
    // right side: F applied to G(w) at cells -1, 0, 1
    const idx = [];
    for (const j of [-1, 0, 1]) {
      let m = 0;
      for (let d = -r; d <= r; d++) m |= at(w, j + d) << (d + r);
      idx.push(m);
    }
    cons.push([idxA, idx[0], idx[1], idx[2]]);
  }
  // DFS over table entries with constraint checking once all four are assigned
  const T = new Int8Array(nEntries).fill(-1);
  const byMax = new Map();
  for (const c of cons) {
    const mx = Math.max(...c);
    if (!byMax.has(mx)) byMax.set(mx, []);
    byMax.get(mx).push(c);
  }
  const sols = [];
  let nodes = 0;
  function dfs(i) {
    if (sols.length > cap) return;
    if (i === nEntries) { sols.push(Array.from(T)); return; }
    for (const v of [0, 1]) {
      T[i] = v;
      nodes++;
      let ok = true;
      for (const [a, b, c, d] of (byMax.get(i) || [])) {
        if (T[a] !== F(T[b], T[c], T[d])) { ok = false; break; }
      }
      if (ok) dfs(i + 1);
    }
    T[i] = -1;
  }
  dfs(0);
  return { sols, nodes, nEntries };
}

function ruleNumberOfRadius1Table(T) {
  // table index bit (j+1) is cell j, so index m has bit2 = right? careful:
  // m |= at(w, j+d) << (d + r) with r = 1 -> d = -1 -> bit 0 is the LEFT cell.
  // Wolfram's numbering: index 4*l + 2*c + r.  So rule number bit
  // (4*l + 2*c + r) = T[ l<<0 | c<<1 | r<<2 ].
  let n = 0;
  for (let l = 0; l < 2; l++) for (let c = 0; c < 2; c++) for (let r = 0; r < 2; r++) {
    const m = l | (c << 1) | (r << 2);
    n |= T[m] << (4 * l + 2 * c + r);
  }
  return n;
}

