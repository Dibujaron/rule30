// ------------------------------------------------------------- binary case
// G : (S^Z)^2 -> S^Z of radius r, table of 2^(2(2r+1)) bits, indexed by the
// pair of windows.  Constraint: G(Fx, Fy) = F(G(x,y)), tested on all pairs of
// windows of length 2r+3.
function binaryCentraliser(r, cap = 1e6) {
  const span = 2 * r + 1;
  const nEntries = 1 << (2 * span);   // (x-window, y-window)
  const winLen = 2 * r + 3;
  const nWin = 1 << winLen;
  const at = (w, j) => (w >> (j + r + 1)) & 1;
  const pack = (wx, wy, j) => {
    let mx = 0, my = 0;
    for (let d = -r; d <= r; d++) { mx |= at(wx, j + d) << (d + r); my |= at(wy, j + d) << (d + r); }
    return mx | (my << span);
  };
  const cons = [];
  for (let wx = 0; wx < nWin; wx++) for (let wy = 0; wy < nWin; wy++) {
    let ax = 0, ay = 0;
    for (let j = -r; j <= r; j++) {
      ax |= F(at(wx, j - 1), at(wx, j), at(wx, j + 1)) << (j + r);
      ay |= F(at(wy, j - 1), at(wy, j), at(wy, j + 1)) << (j + r);
    }
    const idxA = ax | (ay << span);
    cons.push([idxA, pack(wx, wy, -1), pack(wx, wy, 0), pack(wx, wy, 1)]);
  }
  const T = new Int8Array(nEntries).fill(-1);
  const byMax = new Map();
  for (const c of cons) {
    const mx = Math.max(...c);
    if (!byMax.has(mx)) byMax.set(mx, []);
    byMax.get(mx).push(c);
  }
  const sols = [];
  function dfs(i) {
    if (sols.length > cap) return;
    if (i === nEntries) { sols.push(Array.from(T)); return; }
    for (const v of [0, 1]) {
      T[i] = v;
      let ok = true;
      for (const [a, b, c, d] of (byMax.get(i) || [])) if (T[a] !== F(T[b], T[c], T[d])) { ok = false; break; }
      if (ok) dfs(i + 1);
    }
    T[i] = -1;
  }
  dfs(0);
  return { sols, nEntries };
}

