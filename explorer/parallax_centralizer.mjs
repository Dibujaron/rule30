for (const r of [0, 1, 2]) {
  const t0 = Date.now();
  const { sols, nEntries } = binaryCentraliser(r);
  console.log(`  radius ${r}: ${sols.length} solutions out of 2^${nEntries} tables (${Date.now() - t0} ms)`);
  // classify: which depend on only one argument?
  const span = 2 * r + 1;
  let onlyX = 0, onlyY = 0, both = 0;
  for (const T of sols) {
    let depX = false, depY = false;
    for (let m = 0; m < nEntries; m++) {
      for (let b = 0; b < span; b++) if (T[m] !== T[m ^ (1 << b)]) depX = true;
      for (let b = span; b < 2 * span; b++) if (T[m] !== T[m ^ (1 << b)]) depY = true;
    }
    if (depX && depY) both++; else if (depX) onlyX++; else if (depY) onlyY++;
  }
  console.log(`    genuinely binary (depend on both arguments): ${both};  ` +
    `essentially unary in x: ${onlyX};  in y: ${onlyY};  constant: ${sols.length - both - onlyX - onlyY}`);
}
